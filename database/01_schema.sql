-- ---------------------------------------------------------------------
-- Offers
-- ---------------------------------------------------------------------
CREATE TABLE offers (
  offer_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  branch_id            NUMBER        NOT NULL,
  offer_name           VARCHAR2(120) NOT NULL,
  description          VARCHAR2(400),
  offer_type           VARCHAR2(20)  NOT NULL,   -- PERCENTAGE FLAT BOGO COMBO HAPPY_HOUR
  discount_value       NUMBER(12,2)  DEFAULT 0 NOT NULL,
  max_discount_amt     NUMBER(12,2),
  applies_to           VARCHAR2(12)  DEFAULT 'ALL' NOT NULL, -- ALL CATEGORIES ITEMS
  start_date           DATE          NOT NULL,
  end_date             DATE          NOT NULL,
  start_time           VARCHAR2(5),              -- 'HH24:MI'
  end_time             VARCHAR2(5),
  days_of_week         VARCHAR2(20),             -- '1,2,3' (1=Mon) null = all
  is_active            CHAR(1)       DEFAULT 'Y' NOT NULL,
  is_deleted           CHAR(1)       DEFAULT 'N' NOT NULL,
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  created_by           NUMBER,
  updated_at           TIMESTAMP,
  updated_by           NUMBER,
  CONSTRAINT fk_offers_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT ck_offers_type CHECK (offer_type IN ('PERCENTAGE','FLAT','BOGO','COMBO','HAPPY_HOUR')),
  CONSTRAINT ck_offers_applies CHECK (applies_to IN ('ALL','CATEGORIES','ITEMS')),
  CONSTRAINT ck_offers_dates CHECK (end_date >= start_date),
  CONSTRAINT ck_offers_value CHECK (discount_value >= 0),
  CONSTRAINT ck_offers_flags CHECK (is_active IN ('Y','N') AND is_deleted IN ('Y','N'))
);

CREATE TABLE offer_rules (
  offer_rule_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  offer_id             NUMBER        NOT NULL,
  rule_type            VARCHAR2(12)  NOT NULL,   -- CATEGORY | ITEM
  category_id          NUMBER,
  item_id              NUMBER,
  CONSTRAINT fk_rules_offer FOREIGN KEY (offer_id) REFERENCES offers(offer_id),
  CONSTRAINT fk_rules_cat FOREIGN KEY (category_id) REFERENCES menu_categories(category_id),
  CONSTRAINT fk_rules_item FOREIGN KEY (item_id) REFERENCES menu_items(item_id),
  CONSTRAINT ck_rules_type CHECK ((rule_type = 'CATEGORY' AND category_id IS NOT NULL AND item_id IS NULL)
                               OR (rule_type = 'ITEM' AND item_id IS NOT NULL AND category_id IS NULL))
);
CREATE INDEX ix_rules_offer ON offer_rules (offer_id);

