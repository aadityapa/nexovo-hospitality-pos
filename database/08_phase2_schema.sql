CREATE OR REPLACE VIEW v_inventory_status AS
SELECT i.inv_item_id, i.branch_id, i.item_code, i.item_name, c.cat_name, c.cat_kind, u.unit_code,
       i.current_qty, i.min_qty, i.reorder_level, i.avg_cost, i.current_qty * i.avg_cost AS stock_value,
       CASE WHEN i.current_qty <= 0 THEN 'OUT' WHEN i.current_qty <= i.min_qty THEN 'LOW' WHEN i.current_qty <= i.reorder_level THEN 'REORDER' ELSE 'OK' END AS stock_status
FROM inventory_items i JOIN inventory_categories c ON c.inv_cat_id = i.inv_cat_id JOIN inventory_units u ON u.unit_id = i.unit_id
WHERE i.is_deleted = 'N' AND i.is_active = 'Y';

CREATE OR REPLACE VIEW v_supplier_balance AS
SELECT s.supplier_id, s.branch_id,
       NVL((SELECT SUM(g.total_amount) FROM goods_receipts g JOIN purchase_orders p ON p.po_id = g.po_id WHERE p.supplier_id = s.supplier_id), 0) AS total_received_value,
       NVL((SELECT SUM(sp.amount) FROM supplier_payments sp WHERE sp.supplier_id = s.supplier_id), 0) AS total_paid
FROM suppliers s;
