SET DEFINE OFF;

-- ---------------------------------------------------------------------
-- Tenancy / organisation
-- ---------------------------------------------------------------------
CREATE TABLE branches (
  branch_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  branch_code          VARCHAR2(20)  NOT NULL,
  business_name        VARCHAR2(150) NOT NULL,
  branch_name          VARCHAR2(150) NOT NULL,
  address_line         VARCHAR2(400),
  city                 VARCHAR2(100),
  phone                VARCHAR2(30),
  email                VARCHAR2(150),
  gst_number           VARCHAR2(30),
  logo_url             VARCHAR2(500),
  welcome_message      VARCHAR2(300),
  currency_code        VARCHAR2(3)   DEFAULT 'INR' NOT NULL,
  timezone             VARCHAR2(60)  DEFAULT 'Asia/Kolkata' NOT NULL,
  service_charge_pct   NUMBER(5,2)   DEFAULT 0 NOT NULL,
  tax_on_service_chg   CHAR(1)       DEFAULT 'N' NOT NULL,
  rounding_mode        VARCHAR2(10)  DEFAULT 'NEAREST' NOT NULL,
  allow_multi_orders   CHAR(1)       DEFAULT 'N' NOT NULL,
  receipt_footer       VARCHAR2(300) DEFAULT 'Thank you, visit again!',
  is_active            CHAR(1)       DEFAULT 'Y' NOT NULL,
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  created_by           NUMBER,
  updated_at           TIMESTAMP,
  updated_by           NUMBER,
  CONSTRAINT uq_branches_code       UNIQUE (branch_code),
  CONSTRAINT ck_branches_sc_pct     CHECK (service_charge_pct BETWEEN 0 AND 100),
  CONSTRAINT ck_branches_flags      CHECK (tax_on_service_chg IN ('Y','N') AND allow_multi_orders IN ('Y','N') AND is_active IN ('Y','N')),
  CONSTRAINT ck_branches_rounding   CHECK (rounding_mode IN ('NEAREST','UP','DOWN','NONE'))
);

-- ---------------------------------------------------------------------
-- Security
-- ---------------------------------------------------------------------
CREATE TABLE roles (
  role_id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  role_code            VARCHAR2(30)  NOT NULL,
  role_name            VARCHAR2(80)  NOT NULL,
  description          VARCHAR2(300),
  max_discount_pct     NUMBER(5,2)   DEFAULT 0 NOT NULL,
  is_system            CHAR(1)       DEFAULT 'N' NOT NULL,
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at           TIMESTAMP,
  updated_by           NUMBER,
  CONSTRAINT uq_roles_code UNIQUE (role_code),
  CONSTRAINT ck_roles_disc CHECK (max_discount_pct BETWEEN 0 AND 100)
);

CREATE TABLE permissions (
  permission_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  permission_code      VARCHAR2(60)  NOT NULL,
  module_name          VARCHAR2(40)  NOT NULL,
  description          VARCHAR2(200),
  CONSTRAINT uq_permissions_code UNIQUE (permission_code)
);

CREATE TABLE role_permissions (
  role_id              NUMBER NOT NULL,
  permission_id        NUMBER NOT NULL,
  CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id),
  CONSTRAINT fk_rp_role FOREIGN KEY (role_id) REFERENCES roles(role_id),
  CONSTRAINT fk_rp_perm FOREIGN KEY (permission_id) REFERENCES permissions(permission_id)
);

CREATE TABLE users (
  user_id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  branch_id            NUMBER        NOT NULL,
  username             VARCHAR2(60)  NOT NULL,
  email                VARCHAR2(150),
  full_name            VARCHAR2(150) NOT NULL,
  phone                VARCHAR2(30),
  password_hash        RAW(64)       NOT NULL,
  password_salt        RAW(32)       NOT NULL,
  approval_pin_hash    RAW(64),
  is_active            CHAR(1)       DEFAULT 'Y' NOT NULL,
  is_deleted           CHAR(1)       DEFAULT 'N' NOT NULL,
  failed_logins        NUMBER(3)     DEFAULT 0 NOT NULL,
  locked_until         TIMESTAMP,
  last_login_at        TIMESTAMP,
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  created_by           NUMBER,
  updated_at           TIMESTAMP,
  updated_by           NUMBER,
  CONSTRAINT uq_users_username UNIQUE (username),
  CONSTRAINT fk_users_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT ck_users_flags CHECK (is_active IN ('Y','N') AND is_deleted IN ('Y','N'))
);
CREATE UNIQUE INDEX uq_users_email ON users (LOWER(email));

CREATE TABLE user_roles (
  user_id              NUMBER NOT NULL,
  role_id              NUMBER NOT NULL,
  assigned_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  assigned_by          NUMBER,
  CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
  CONSTRAINT fk_ur_user FOREIGN KEY (user_id) REFERENCES users(user_id),
  CONSTRAINT fk_ur_role FOREIGN KEY (role_id) REFERENCES roles(role_id)
);

CREATE TABLE user_sessions (
  session_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id              NUMBER        NOT NULL,
  token_hash           RAW(64)       NOT NULL,
  issued_at            TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  expires_at           TIMESTAMP     NOT NULL,
  revoked_at           TIMESTAMP,
  ip_address           VARCHAR2(60),
  user_agent           VARCHAR2(400),
  CONSTRAINT uq_sessions_token UNIQUE (token_hash),
  CONSTRAINT fk_sessions_user FOREIGN KEY (user_id) REFERENCES users(user_id)
);
CREATE INDEX ix_sessions_user ON user_sessions (user_id, expires_at);

-- ---------------------------------------------------------------------
-- Layout: floors & tables
-- ---------------------------------------------------------------------
CREATE TABLE floors (
  floor_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  branch_id            NUMBER        NOT NULL,
  floor_code           VARCHAR2(20)  NOT NULL,
  floor_name           VARCHAR2(100) NOT NULL,
  display_order        NUMBER(4)     DEFAULT 0 NOT NULL,
  is_active            CHAR(1)       DEFAULT 'Y' NOT NULL,
  is_deleted           CHAR(1)       DEFAULT 'N' NOT NULL,
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  created_by           NUMBER,
  updated_at           TIMESTAMP,
  updated_by           NUMBER,
  CONSTRAINT uq_floors_code UNIQUE (branch_id, floor_code),
  CONSTRAINT fk_floors_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT ck_floors_flags CHECK (is_active IN ('Y','N') AND is_deleted IN ('Y','N'))
);

CREATE TABLE dining_tables (
  table_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  branch_id            NUMBER        NOT NULL,
  floor_id             NUMBER        NOT NULL,
  table_number         VARCHAR2(20)  NOT NULL,
  table_name           VARCHAR2(60)  NOT NULL,
  seating_capacity     NUMBER(3)     DEFAULT 4 NOT NULL,
  public_code          VARCHAR2(32)  NOT NULL,      -- opaque token used in QR URL
  qr_version           NUMBER(5)     DEFAULT 1 NOT NULL,
  status               VARCHAR2(20)  DEFAULT 'AVAILABLE' NOT NULL,
  status_override      CHAR(1)       DEFAULT 'N' NOT NULL, -- Y = manually set, not derived
  assigned_waiter_id   NUMBER,
  is_active            CHAR(1)       DEFAULT 'Y' NOT NULL,
  is_deleted           CHAR(1)       DEFAULT 'N' NOT NULL,
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  created_by           NUMBER,
  updated_at           TIMESTAMP,
  updated_by           NUMBER,
  CONSTRAINT uq_tables_number UNIQUE (branch_id, table_number),
  CONSTRAINT uq_tables_public UNIQUE (public_code),
  CONSTRAINT fk_tables_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT fk_tables_floor  FOREIGN KEY (floor_id)  REFERENCES floors(floor_id),
  CONSTRAINT fk_tables_waiter FOREIGN KEY (assigned_waiter_id) REFERENCES users(user_id),
  CONSTRAINT ck_tables_capacity CHECK (seating_capacity > 0),
  CONSTRAINT ck_tables_status CHECK (status IN ('AVAILABLE','OCCUPIED','ORDERING','PREPARING','READY','BILLING','PAYMENT_PENDING','CLOSED')),
  CONSTRAINT ck_tables_flags CHECK (status_override IN ('Y','N') AND is_active IN ('Y','N') AND is_deleted IN ('Y','N'))
);
CREATE INDEX ix_tables_floor ON dining_tables (floor_id);
CREATE INDEX ix_tables_waiter ON dining_tables (assigned_waiter_id);

