-- ---------------------------------------------------------------------
-- Orders
-- ---------------------------------------------------------------------
CREATE TABLE orders (
  order_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  order_number         VARCHAR2(30)  NOT NULL,
  branch_id            NUMBER        NOT NULL,
  table_id             NUMBER        NOT NULL,
  waiter_id            NUMBER        NOT NULL,
  order_type           VARCHAR2(20)  DEFAULT 'DINE_IN' NOT NULL,
  status               VARCHAR2(20)  DEFAULT 'DRAFT' NOT NULL,
  guest_count          NUMBER(3)     DEFAULT 1,
  notes                VARCHAR2(500),
  subtotal             NUMBER(12,2)  DEFAULT 0 NOT NULL,   -- cached Σ active lines
  reference_type       VARCHAR2(30),                       -- Phase-2: ROOM, RESERVATION …
  reference_id         NUMBER,
  confirmed_at         TIMESTAMP,
  bill_requested_at    TIMESTAMP,
  completed_at         TIMESTAMP,
  cancelled_at         TIMESTAMP,
  cancelled_by         NUMBER,
  cancel_reason        VARCHAR2(300),
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  created_by           NUMBER,
  updated_at           TIMESTAMP,
  updated_by           NUMBER,
  CONSTRAINT uq_orders_number UNIQUE (order_number),
  CONSTRAINT fk_orders_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT fk_orders_table  FOREIGN KEY (table_id)  REFERENCES dining_tables(table_id),
  CONSTRAINT fk_orders_waiter FOREIGN KEY (waiter_id) REFERENCES users(user_id),
  CONSTRAINT ck_orders_status CHECK (status IN ('DRAFT','CONFIRMED','IN_PROGRESS','PARTIALLY_READY','READY','SERVED','BILL_REQUESTED','BILLED','PAID','COMPLETED','CANCELLED')),
  CONSTRAINT ck_orders_type CHECK (order_type IN ('DINE_IN','TAKEAWAY','ROOM_SERVICE','DELIVERY'))
);
CREATE INDEX ix_orders_table_status ON orders (table_id, status);
CREATE INDEX ix_orders_status ON orders (branch_id, status);
CREATE INDEX ix_orders_created ON orders (branch_id, created_at);
CREATE INDEX ix_orders_waiter ON orders (waiter_id);
-- Rule 2: one active order per table (unless branch allows multiples — enforced in ORDER_PKG)
CREATE UNIQUE INDEX uq_orders_active_table ON orders (
  CASE WHEN status NOT IN ('COMPLETED','CANCELLED') THEN table_id END
);

