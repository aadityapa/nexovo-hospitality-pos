  CONSTRAINT fk_invcat_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT ck_invcat_kind CHECK (cat_kind IN ('INGREDIENT','RAW_MATERIAL','BEVERAGE','BOTTLE','PACKAGING','CONSUMABLE'))
);

