CREATE TABLE inventory_items (
  inv_item_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  branch_id            NUMBER        NOT NULL,
  inv_cat_id           NUMBER        NOT NULL,
  item_code            VARCHAR2(30)  NOT NULL,
  item_name            VARCHAR2(150) NOT NULL,
  unit_id              NUMBER        NOT NULL,      -- stock-keeping unit (e.g. KG)
  pack_size            NUMBER(12,4),                -- optional: base units per PIECE/BOTTLE (750 ml bottle)
  current_qty          NUMBER(14,4)  DEFAULT 0 NOT NULL,
  min_qty              NUMBER(14,4)  DEFAULT 0 NOT NULL,
  max_qty              NUMBER(14,4),
  reorder_level        NUMBER(14,4)  DEFAULT 0 NOT NULL,
  cost_price           NUMBER(12,4)  DEFAULT 0 NOT NULL,   -- last purchase price per unit
  avg_cost             NUMBER(12,4)  DEFAULT 0 NOT NULL,   -- moving average per unit
  supplier_id          NUMBER,
  allow_negative       CHAR(1)       DEFAULT 'N' NOT NULL,
  is_active            CHAR(1)       DEFAULT 'Y' NOT NULL,
  is_deleted           CHAR(1)       DEFAULT 'N' NOT NULL,
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  created_by           NUMBER,
  updated_at           TIMESTAMP,
  updated_by           NUMBER,
  CONSTRAINT uq_invitem_code UNIQUE (branch_id, item_code),
  CONSTRAINT fk_invitem_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT fk_invitem_cat FOREIGN KEY (inv_cat_id) REFERENCES inventory_categories(inv_cat_id),
  CONSTRAINT fk_invitem_unit FOREIGN KEY (unit_id) REFERENCES inventory_units(unit_id),
  CONSTRAINT fk_invitem_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id),
  CONSTRAINT ck_invitem_flags CHECK (allow_negative IN ('Y','N') AND is_active IN ('Y','N') AND is_deleted IN ('Y','N')),
  CONSTRAINT ck_invitem_qty CHECK (min_qty >= 0 AND reorder_level >= 0 AND cost_price >= 0 AND avg_cost >= 0)
);
CREATE INDEX ix_invitem_cat ON inventory_items (inv_cat_id);
CREATE INDEX ix_invitem_low ON inventory_items (branch_id, current_qty, min_qty);

-- Every stock change is a movement (never overwrite quantities directly)
CREATE TABLE stock_movements (
  mvt_id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  branch_id            NUMBER        NOT NULL,
  inv_item_id          NUMBER        NOT NULL,
  mvt_type             VARCHAR2(20)  NOT NULL,
  qty                  NUMBER(14,4)  NOT NULL,      -- signed, in item unit (+in / -out)
  qty_before           NUMBER(14,4)  NOT NULL,
  qty_after            NUMBER(14,4)  NOT NULL,
  unit_cost            NUMBER(12,4)  DEFAULT 0 NOT NULL,
  total_cost           NUMBER(14,2)  DEFAULT 0 NOT NULL,
  ref_type             VARCHAR2(30),                -- ORDER_ITEM, GRN, PO, ADJUSTMENT …
  ref_id               NUMBER,
  idempotency_key      VARCHAR2(120),               -- e.g. ORDER_ITEM:123:DEDUCT — prevents double deduction/reversal
  reason               VARCHAR2(300),
  created_by           NUMBER,
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_mvt_idem UNIQUE (idempotency_key),
  CONSTRAINT fk_mvt_item FOREIGN KEY (inv_item_id) REFERENCES inventory_items(inv_item_id),
  CONSTRAINT fk_mvt_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT ck_mvt_type CHECK (mvt_type IN ('PURCHASE','SALE_CONSUMPTION','WASTAGE','DAMAGE','RETURN','TRANSFER','ADJUSTMENT','OPENING_STOCK','CONSUMPTION_REVERSAL'))
);
CREATE INDEX ix_mvt_item ON stock_movements (inv_item_id, created_at);
CREATE INDEX ix_mvt_branch ON stock_movements (branch_id, created_at);

