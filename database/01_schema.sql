CREATE OR REPLACE VIEW v_active_orders AS
SELECT o.order_id, o.order_number, o.branch_id, o.table_id, t.table_name, t.table_number,
       f.floor_name, o.waiter_id, u.full_name AS waiter_name, o.status, o.subtotal,
       o.guest_count, o.notes, o.created_at, o.confirmed_at, o.bill_requested_at,
       (SELECT COUNT(*) FROM order_items oi WHERE oi.order_id = o.order_id AND oi.status <> 'CANCELLED') AS item_count
FROM orders o
JOIN dining_tables t ON t.table_id = o.table_id
JOIN floors f ON f.floor_id = t.floor_id
JOIN users u ON u.user_id = o.waiter_id
WHERE o.status NOT IN ('COMPLETED','CANCELLED');

CREATE OR REPLACE VIEW v_user_permissions AS
SELECT DISTINCT ur.user_id, p.permission_code
FROM user_roles ur
JOIN role_permissions rp ON rp.role_id = ur.role_id
JOIN permissions p ON p.permission_id = rp.permission_id;

CREATE OR REPLACE VIEW v_offer_active AS
SELECT o.*,
       CASE WHEN o.is_active = 'Y' AND o.is_deleted = 'N'
             AND TRUNC(SYSDATE) BETWEEN o.start_date AND o.end_date
             AND (o.start_time IS NULL OR TO_CHAR(SYSDATE,'HH24:MI') >= o.start_time)
             AND (o.end_time   IS NULL OR TO_CHAR(SYSDATE,'HH24:MI') <= o.end_time)
             AND (o.days_of_week IS NULL OR INSTR(','||o.days_of_week||',', ','||TO_CHAR(SYSDATE,'ID')||',') > 0)  -- ISO weekday: 1 = Monday
            THEN 'Y' ELSE 'N' END AS is_currently_active
FROM offers o;
