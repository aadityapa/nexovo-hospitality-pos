-- ---------------------------------------------------------------------
-- Inventory
-- ---------------------------------------------------------------------
CREATE TABLE inventory_units (
  unit_id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  unit_code            VARCHAR2(10)  NOT NULL,
  unit_name            VARCHAR2(40)  NOT NULL,
  base_unit_code       VARCHAR2(10)  NOT NULL,   -- unit family: G, ML, PIECE
  factor_to_base       NUMBER(14,6)  NOT NULL,   -- 1 unit = factor base units (KG → 1000 G)
  CONSTRAINT uq_unit_code UNIQUE (unit_code),
  CONSTRAINT ck_unit_factor CHECK (factor_to_base > 0)
);
-- explicit cross-family conversions (e.g. BOTTLE → ML for a specific item are kept on the item as pack_size)
CREATE TABLE unit_conversions (
  conversion_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  from_unit_id         NUMBER NOT NULL,
  to_unit_id           NUMBER NOT NULL,
  factor               NUMBER(14,6) NOT NULL,
  CONSTRAINT uq_unit_conv UNIQUE (from_unit_id, to_unit_id),
  CONSTRAINT fk_uc_from FOREIGN KEY (from_unit_id) REFERENCES inventory_units(unit_id),
  CONSTRAINT fk_uc_to   FOREIGN KEY (to_unit_id)   REFERENCES inventory_units(unit_id),
  CONSTRAINT ck_uc_factor CHECK (factor > 0)
);

CREATE TABLE inventory_categories (
  inv_cat_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  branch_id            NUMBER        NOT NULL,
  cat_name             VARCHAR2(80)  NOT NULL,
