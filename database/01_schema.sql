CREATE TABLE bill_items (
  bill_item_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  bill_id              NUMBER        NOT NULL,
  order_item_id        NUMBER        NOT NULL,
  item_name            VARCHAR2(150) NOT NULL,
  quantity             NUMBER(6,2)   NOT NULL,
  unit_price           NUMBER(12,2)  NOT NULL,
  line_total           NUMBER(12,2)  NOT NULL,
  discount_amount      NUMBER(12,2)  DEFAULT 0 NOT NULL,   -- item-level (offer)
  taxable_amount       NUMBER(12,2)  DEFAULT 0 NOT NULL,
  tax_group_id         NUMBER        NOT NULL,
  tax_pct              NUMBER(6,3)   DEFAULT 0 NOT NULL,
  tax_amount           NUMBER(12,2)  DEFAULT 0 NOT NULL,
  offer_id             NUMBER,
  CONSTRAINT fk_bi_bill FOREIGN KEY (bill_id) REFERENCES bills(bill_id),
  CONSTRAINT fk_bi_oi FOREIGN KEY (order_item_id) REFERENCES order_items(order_item_id),
  CONSTRAINT fk_bi_tax FOREIGN KEY (tax_group_id) REFERENCES tax_configurations(tax_group_id),
  CONSTRAINT fk_bi_offer FOREIGN KEY (offer_id) REFERENCES offers(offer_id),
  CONSTRAINT ck_bi_amounts CHECK (quantity > 0 AND unit_price >= 0 AND discount_amount >= 0)
);
CREATE INDEX ix_bi_bill ON bill_items (bill_id);

