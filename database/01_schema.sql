CREATE TABLE tax_components (
  tax_component_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  tax_group_id         NUMBER        NOT NULL,
  component_code       VARCHAR2(20)  NOT NULL,   -- CGST / SGST / IGST / VAT / CESS
  component_name       VARCHAR2(80)  NOT NULL,
