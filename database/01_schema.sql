-- ---------------------------------------------------------------------
-- Billing
-- ---------------------------------------------------------------------
CREATE TABLE bills (
  bill_id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  bill_number          VARCHAR2(30)  NOT NULL,
  branch_id            NUMBER        NOT NULL,
  order_id             NUMBER        NOT NULL,
  cashier_id           NUMBER        NOT NULL,
  status               VARCHAR2(20)  DEFAULT 'OPEN' NOT NULL,      -- OPEN FINALIZED PAID CLOSED VOID
  payment_status       VARCHAR2(20)  DEFAULT 'UNPAID' NOT NULL,    -- UNPAID PARTIALLY_PAID PAID REFUNDED
  subtotal             NUMBER(12,2)  DEFAULT 0 NOT NULL,
  item_discount_total  NUMBER(12,2)  DEFAULT 0 NOT NULL,
  order_discount_total NUMBER(12,2)  DEFAULT 0 NOT NULL,
  service_charge_pct   NUMBER(5,2)   DEFAULT 0 NOT NULL,
  service_charge_amt   NUMBER(12,2)  DEFAULT 0 NOT NULL,
  tax_total            NUMBER(12,2)  DEFAULT 0 NOT NULL,
  round_off            NUMBER(6,2)   DEFAULT 0 NOT NULL,
  grand_total          NUMBER(12,2)  DEFAULT 0 NOT NULL,
  paid_amount          NUMBER(12,2)  DEFAULT 0 NOT NULL,
  notes                VARCHAR2(400),
  finalized_at         TIMESTAMP,
  paid_at              TIMESTAMP,
  closed_at            TIMESTAMP,
  voided_at            TIMESTAMP,
  void_reason          VARCHAR2(300),
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  created_by           NUMBER,
  updated_at           TIMESTAMP,
  updated_by           NUMBER,
  CONSTRAINT uq_bills_number UNIQUE (bill_number),
  CONSTRAINT fk_bills_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT fk_bills_order FOREIGN KEY (order_id) REFERENCES orders(order_id),
  CONSTRAINT fk_bills_cashier FOREIGN KEY (cashier_id) REFERENCES users(user_id),
  CONSTRAINT ck_bills_status CHECK (status IN ('OPEN','FINALIZED','PAID','CLOSED','VOID')),
  CONSTRAINT ck_bills_pstatus CHECK (payment_status IN ('UNPAID','PARTIALLY_PAID','PAID','REFUNDED')),
  CONSTRAINT ck_bills_amounts CHECK (subtotal >= 0 AND grand_total >= 0 AND paid_amount >= 0)
);
CREATE INDEX ix_bills_order ON bills (order_id);
CREATE INDEX ix_bills_status ON bills (branch_id, status, payment_status);
CREATE INDEX ix_bills_created ON bills (branch_id, created_at);
