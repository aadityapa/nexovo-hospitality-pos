CREATE TABLE recipe_items (
  recipe_item_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  recipe_id            NUMBER        NOT NULL,
  inv_item_id          NUMBER        NOT NULL,
