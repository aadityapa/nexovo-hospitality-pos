CREATE TABLE payments (
  payment_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  payment_number       VARCHAR2(30)  NOT NULL,
  bill_id              NUMBER        NOT NULL,
  payment_method       VARCHAR2(20)  NOT NULL,   -- CASH UPI CARD COMPLIMENTARY (lookup, extensible)
  amount               NUMBER(12,2)  NOT NULL,
  reference_no         VARCHAR2(100),
  status               VARCHAR2(20)  DEFAULT 'SUCCESS' NOT NULL,   -- SUCCESS REVERSED
  received_by          NUMBER        NOT NULL,
  received_at          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  reversed_at          TIMESTAMP,
  reversed_by          NUMBER,
  reversal_reason      VARCHAR2(300),
  CONSTRAINT uq_pay_number UNIQUE (payment_number),
  CONSTRAINT fk_pay_bill FOREIGN KEY (bill_id) REFERENCES bills(bill_id),
  CONSTRAINT fk_pay_user FOREIGN KEY (received_by) REFERENCES users(user_id),
  CONSTRAINT ck_pay_amount CHECK (amount > 0),
  CONSTRAINT ck_pay_status CHECK (status IN ('SUCCESS','REVERSED'))
);
CREATE INDEX ix_pay_bill ON payments (bill_id);
CREATE INDEX ix_pay_received ON payments (received_at);

-- Gateway / device level transactions (Phase-1: manual entries; Phase-2: PG callbacks)
