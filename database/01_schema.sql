CREATE TABLE discounts (
  discount_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  bill_id              NUMBER        NOT NULL,
  discount_type        VARCHAR2(20)  NOT NULL,   -- PERCENTAGE FLAT OFFER
  discount_value       NUMBER(12,2)  NOT NULL,
  discount_amount      NUMBER(12,2)  NOT NULL,
  reason               VARCHAR2(300) NOT NULL,
  offer_id             NUMBER,
  applied_by           NUMBER        NOT NULL,
  approved_by          NUMBER,
  is_voided            CHAR(1)       DEFAULT 'N' NOT NULL,
  voided_at            TIMESTAMP,
  voided_by            NUMBER,
  created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_disc_bill FOREIGN KEY (bill_id) REFERENCES bills(bill_id),
  CONSTRAINT fk_disc_offer FOREIGN KEY (offer_id) REFERENCES offers(offer_id),
  CONSTRAINT fk_disc_applied FOREIGN KEY (applied_by) REFERENCES users(user_id),
  CONSTRAINT fk_disc_approved FOREIGN KEY (approved_by) REFERENCES users(user_id),
  CONSTRAINT ck_disc_type CHECK (discount_type IN ('PERCENTAGE','FLAT','OFFER')),
  CONSTRAINT ck_disc_amounts CHECK (discount_value >= 0 AND discount_amount >= 0),
  CONSTRAINT ck_disc_void CHECK (is_voided IN ('Y','N'))
);
CREATE INDEX ix_disc_bill ON discounts (bill_id);

