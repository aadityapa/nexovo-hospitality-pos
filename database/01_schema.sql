  CONSTRAINT uq_tax_comp UNIQUE (tax_group_id, component_code),
  CONSTRAINT fk_tax_comp_group FOREIGN KEY (tax_group_id) REFERENCES tax_configurations(tax_group_id),
  CONSTRAINT ck_tax_comp_rate CHECK (rate_pct >= 0)
